/*
Operadores Lógicos:

&& -> AND -> E
|| -> OR -> OU
! -> NOT -> NÃO
*/

// && -> todas as expressões precisam ser verdadeiras
console.log(true && true);
console.log(true && false);

// || -> pelo menos uma expressão precisa ser verdadeira
console.log(true || true);
console.log(true || false);
console.log(false || false);

// ! -> negação/inverter valor

console.log(!false);
console.log(!!false);